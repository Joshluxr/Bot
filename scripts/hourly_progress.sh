#!/bin/bash
# Hourly progress logger for SearchK4
# Appends per-GPU progress to range7_progress.log every 3600 seconds
# Run in background: nohup bash hourly_progress.sh &

cd /root/searchk4_hybrid/SearchK4_optimized
LOGFILE="range7_progress.log"

# Decimal ranges for documentation in log
GPU_STARTS=(
  "82988190356384517260073324955726623558128682318812983971013110423526066342990"
  "82988190356384517260073324955726623558128682318812983971013111673526066342990"
  "82988190356384517260073324955726623558128682318812983971013112923526066342990"
  "82988190356384517260073324955726623558128682318812983971013114173526066342990"
  "82988190356384517260073324955726623558128682318812983971013115423526066342990"
  "82988190356384517260073324955726623558128682318812983971013116673526066342990"
  "82988190356384517260073324955726623558128682318812983971013117923526066342990"
  "82988190356384517260073324955726623558128682318812983971013119173526066342990"
)

GPU_ENDS=(
  "82988190356384517260073324955726623558128682318812983971013111673526066342989"
  "82988190356384517260073324955726623558128682318812983971013112923526066342989"
  "82988190356384517260073324955726623558128682318812983971013114173526066342989"
  "82988190356384517260073324955726623558128682318812983971013115423526066342989"
  "82988190356384517260073324955726623558128682318812983971013116673526066342989"
  "82988190356384517260073324955726623558128682318812983971013117923526066342989"
  "82988190356384517260073324955726623558128682318812983971013119173526066342989"
  "82988190356384517260073324955726623558128682318812983971013120423526066342990"
)

while true; do
  TIMESTAMP=$(date -u '+%Y-%m-%d %H:%M:%S UTC')
  echo "========================================" >> "$LOGFILE"
  echo "Progress Report: $TIMESTAMP" >> "$LOGFILE"
  echo "========================================" >> "$LOGFILE"

  TOTAL_KEYS=0
  for i in {0..7}; do
    COVERED=$(grep "Covered:" "gpu${i}_r7.log" 2>/dev/null | tail -1 | sed 's/.*Covered: \([0-9.]*\)B keys.*/\1/')
    SPEED=$(grep "GKey/s" "gpu${i}_r7.log" 2>/dev/null | tail -1 | sed 's/.*| \([0-9.]*\) GKey\/s.*/\1/')
    MATCH_STATUS="NO MATCH"
    if [ -s "gpu${i}_r7_found.txt" ]; then
      MATCH_STATUS="*** MATCH FOUND ***"
      cat "gpu${i}_r7_found.txt" >> "$LOGFILE"
    fi
    echo "GPU $i: Covered ${COVERED:-0}B keys | ${SPEED:-N/A} GKey/s | From: ${GPU_STARTS[$i]} | To: ${GPU_ENDS[$i]} | $MATCH_STATUS" >> "$LOGFILE"
  done

  echo "" >> "$LOGFILE"
  sleep 3600
done
